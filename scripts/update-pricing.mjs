import { writeFile } from "node:fs/promises"

const providers = [
  "openai",
  "anthropic",
  "google",
  "moonshotai",
  "moonshotai-cn",
  "deepseek",
  "xai",
  "mistral",
]

const response = await fetch("https://models.dev/api.json", {
  headers: { accept: "application/json", "user-agent": "opencode-metrics-price-update" },
  signal: AbortSignal.timeout(30_000),
})
if (!response.ok) throw new Error(`models.dev returned HTTP ${response.status}`)
const input = await response.json()
const catalog = {}

function price(cost) {
  return {
    input: cost.input ?? 0,
    output: cost.output ?? 0,
    cacheRead: cost.cache_read ?? 0,
    cacheWrite: cost.cache_write ?? 0,
    ...(cost.tier?.type === "context" ? { tier: { type: "context", size: cost.tier.size } } : {}),
  }
}

for (const providerID of providers) {
  const models = input[providerID]?.models ?? {}
  catalog[providerID] = {}
  for (const [modelID, model] of Object.entries(models)) {
    if (!model.cost) continue
    catalog[providerID][modelID] = [price(model.cost), ...(model.cost.tiers ?? []).map(price)]
  }
}

const fetchedAt = Date.now()
const source = `// Generated by scripts/update-pricing.mjs from https://models.dev/api.json.
// Run npm run pricing:update to refresh the offline public API price snapshot.
import type { ApiCatalog } from "./pricing.js"

export const FALLBACK_PRICING_FETCHED_AT = ${fetchedAt}
export const FALLBACK_PRICING: ApiCatalog = ${JSON.stringify(catalog, null, 2)}
`
await writeFile(new URL("../src/pricing-fallback.ts", import.meta.url), source)
console.log(`Wrote ${Object.keys(catalog).length} providers and ${Object.values(catalog).reduce((sum, models) => sum + Object.keys(models).length, 0)} models from ${new Date(fetchedAt).toISOString()}`)
